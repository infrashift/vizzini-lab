#!/usr/bin/env bash
# ci-github.sh: run Vizzini's GitHub Actions template for real.
#
#   uat/ci-github.sh
#
# On throwaway branches of this repository (infrashift/vizzini-uat), the
# template deploy/ci/github/vizzini-bot.yml from the pinned Vizzini commit runs
# on a real pull request, on GitHub's runners, with GITHUB_TOKEN. The test
# changes the template in one way only: the model is Vizzini's stubllm, started
# inside the job with -finding-per-file. LiteLLM on this machine is not
# reachable from GitHub's runners, and tokens are not the point. The
# onboarding sequence of deploy/ci/README.md is then played out:
#
#   1. base branch ci/base-<stamp>: a small Go file and the template's grant
#      policy, which lists no identity
#   2. PR from ci/pr-<stamp>: the file changed, plus the test workflow
#      -> the run must fail with exit 3, nothing posted; its log names the
#         identity GITHUB_TOKEN posts as
#   3. that identity committed to the base's policy, the run re-run
#      -> it must post the stub's findings as review comments with markers
#   4. a second commit to the PR
#      -> an incremental run of the changed file only; no comment duplicated
#   5. the PR closed and both branches deleted
#
# Needs gh (authenticated), the pinned Vizzini clone (uat/build.sh vizzini) and
# python3 with PyYAML. Writes .cache/runs/<UTC>-ci-github/; exits non-zero when
# a check fails.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=versions.env
source "$root/versions.env"
gh_repo="${CI_GITHUB_REPO:-infrashift/vizzini-uat}"
vz="$root/.cache/src/vizzini"
template="$vz/deploy/ci/github/vizzini-bot.yml"

say() { printf '\n== %s\n' "$*"; }
die() { printf 'ci-github: %s\n' "$*" >&2; exit 1; }
[[ -f $template ]] || die "no $template: pin a Vizzini commit with deploy/ci (uat/build.sh vizzini)"

stamp="$(date -u +%Y%m%dT%H%M%SZ)"
run="$root/.cache/runs/$stamp-ci-github"
base="ci/base-$stamp" head="ci/pr-$stamp"
mkdir -p "$run"
echo "run: $run"

# The test workflow: the template, with stubllm as the model.
python3 -I - "$template" "$run/vizzini-bot.yml" <<'EOF'
import sys, yaml
wf = yaml.safe_load(open(sys.argv[1]))
# YAML 1.1 reads the key "on" as true; keep it "on", in its place.
wf = {("on" if k is True else k): v for k, v in wf.items()}
steps = wf["jobs"]["review"]["steps"]
i = next(n for n, s in enumerate(steps) if s.get("name", "").startswith("Install"))
steps.insert(i + 1, {
    "name": "Start stubllm as the model (vizzini-uat test only)",
    "run": "(cd .vizzini-src && go build -o \"$RUNNER_TEMP/stubllm\" ./scripts/e2e/stubllm)\n"
           "nohup \"$RUNNER_TEMP/stubllm\" -addr 127.0.0.1:18765 -finding-per-file >\"$RUNNER_TEMP/stubllm.log\" 2>&1 &\n"
           "for _ in $(seq 50); do curl -s -o /dev/null http://127.0.0.1:18765/ && break; sleep 0.2; done\n",
})
review = next(s for s in steps if s.get("name") == "Review")
review["env"].update({"VIZZINI_LITELLM_URL": "http://127.0.0.1:18765/v1", "VIZZINI_MODEL": "stub", "VIZZINI_API_KEY": ""})
open(sys.argv[2], "w").write("# Generated by vizzini-uat uat/ci-github.sh from Vizzini's deploy/ci/github/vizzini-bot.yml;\n"
                             "# the only change: stubllm, started in the job, is the model.\n" + yaml.safe_dump(wf, sort_keys=False))
EOF
diff <(python3 -I -c 'import sys,yaml,json; print(json.dumps({str(k): v for k, v in yaml.safe_load(open(sys.argv[1])).items()},indent=1,sort_keys=True))' "$template") \
	<(python3 -I -c 'import sys,yaml,json; print(json.dumps({str(k): v for k, v in yaml.safe_load(open(sys.argv[1])).items()},indent=1,sort_keys=True))' "$run/vizzini-bot.yml") \
	>"$run/workflow.diff" || true
echo "   test workflow: the template plus $(grep -c '^>' "$run/workflow.diff") changed line(s) (workflow.diff)"

say "branches $base and $head"
repo="$run/repo"
git init -q -b "$base" "$repo"
g() { git -C "$repo" -c user.name=vizzini-uat -c user.email=uat@example.invalid "$@"; }
mkdir -p "$repo/calc" "$repo/.vizzini/grant-policy"
cat >"$repo/calc/calc.go" <<'EOF'
package calc

// Add returns a + b.
func Add(a, b int) int { return a + b }
EOF
cp "$vz/deploy/ci/grant-policy/agent-submit.cue" "$repo/.vizzini/grant-policy/agent-submit.cue"
g add -A
g commit -qm "ci test base: calc and the template's grant policy (no identity) [skip ci]"
g checkout -qb "$head"
cat >>"$repo/calc/calc.go" <<'EOF'

// Div returns a / b.
func Div(a, b int) int { return a / b }
EOF
mkdir -p "$repo/.github/workflows"
cp "$run/vizzini-bot.yml" "$repo/.github/workflows/vizzini-bot.yml"
g add -A
g commit -qm "ci test: Div, and the vizzini-bot workflow"
g remote add origin "https://github.com/$gh_repo.git"
g push -q origin "$base" "$head"
pr_url="$(gh pr create -R "$gh_repo" --base "$base" --head "$head" --title "vizzini-uat CI template test $stamp" \
	--body "Throwaway PR: runs Vizzini's GitHub Actions template (uat/ci-github.sh). Closed by the script.")"
echo "$pr_url" >"$run/pr-url"
pr="${pr_url##*/}"
echo "   PR: $pr_url"

# wait_run SHA: the vizzini-bot run for SHA, once completed; prints its id.
wait_run() {
	local sha=$1 id="" status="" waited=0
	while ((waited < 900)); do
		read -r id status < <(gh run list -R "$gh_repo" --workflow vizzini-bot --commit "$sha" --limit 1 \
			--json databaseId,status -q '.[0] | "\(.databaseId) \(.status)"' 2>/dev/null || true)
		[[ -n $id && $status == completed ]] && { echo "$id"; return 0; }
		sleep 15
		waited=$((waited + 15))
	done
	die "no completed vizzini-bot run for $sha after 900s"
}

# run_log ID NAME: the run's log and conclusion into $run/NAME.{log,conclusion}.
run_log() {
	gh run view "$1" -R "$gh_repo" --log >"$run/$2.log" 2>&1 || true
	gh run view "$1" -R "$gh_repo" --json conclusion -q .conclusion >"$run/$2.conclusion"
	echo "   run $1: $(<"$run/$2.conclusion")"
}

say "run 1: the policy lists no identity"
sha1="$(g rev-parse HEAD)"
id1="$(wait_run "$sha1")"
run_log "$id1" run1
identity="$(python3 -I - "$run/run1.log" <<'EOF'
import json, re, sys
for line in open(sys.argv[1], errors="replace"):
    m = re.search(r"mrman: authorization: (\{.*\})\s*$", line)
    if m:
        print(json.loads(m.group(1))["input"]["identity"])
        break
EOF
)"
[[ -n $identity ]] || die "run 1 printed no authorization; see $run/run1.log"
echo "   GITHUB_TOKEN posts as: $identity"

say "allow $identity on the base branch, re-run"
g checkout -q "$base"
python3 -I - "$repo/.vizzini/grant-policy/agent-submit.cue" "$identity" <<'EOF'
import json, sys
p, ident = sys.argv[1:]
s = open(p).read()
assert s.count("_allowedIdentities: []") == 1
open(p, "w").write(s.replace("_allowedIdentities: []", "_allowedIdentities: [" + json.dumps(ident) + "]"))
EOF
g commit -qam "ci test base: allow $identity [skip ci]"
g push -q origin "$base"
g checkout -q "$head"
gh run rerun "$id1" -R "$gh_repo"
sleep 20
for _ in $(seq 60); do
	read -r att st < <(gh api "repos/$gh_repo/actions/runs/$id1" -q '"\(.run_attempt) \(.status)"')
	[[ $att -ge 2 && $st == completed ]] && break
	sleep 15
done
run_log "$id1" run2
gh api "repos/$gh_repo/pulls/$pr/comments" >"$run/comments2.json"

say "run 3: a second commit"
cat >>"$repo/calc/calc.go" <<'EOF'

// Mod returns a % b.
func Mod(a, b int) int { return a % b }
EOF
g commit -qam "ci test: Mod"
g push -q origin "$head"
sha3="$(g rev-parse HEAD)"
id3="$(wait_run "$sha3")"
run_log "$id3" run3
gh api "repos/$gh_repo/pulls/$pr/comments" >"$run/comments3.json"

say "close the PR, delete the branches"
gh pr close "$pr" -R "$gh_repo" --delete-branch >/dev/null 2>&1 || true
git -C "$repo" push -q origin --delete "$base" 2>/dev/null || true

say "checks"
python3 -I - "$run" "$identity" <<'EOF' | tee "$run/summary.md"
import json, os, re, sys
run, identity = sys.argv[1:]
ok = True
def check(cond, what):
    global ok
    ok &= bool(cond)
    print(("- [x] " if cond else "- [ ] ") + what)
read = lambda n: open(os.path.join(run, n), errors="replace").read()
marker = re.compile(r"<!-- vizzini:fp=(\S+) run=(\S+)")

print("# vizzini-bot GitHub Actions template, live\n")
print("## run 1: the policy lists no identity\n")
log1 = read("run1.log")
check(read("run1.conclusion").strip() == "failure", "the run failed")
check("exit code 3" in log1, "vizzini-bot exited 3 (the grant policy denied posting)")
check('"decision":"deny"' in log1 and "MRM-002" in log1, "denied by MRM-002 (identity not listed)")
check(identity, f"the log names the identity GITHUB_TOKEN posts as ({identity})")
check("install: done" in log1 and "mrman version v0.1.5" in log1, "install.sh built and verified the tools on the runner")

print("\n## run 2: the identity allowed on the base branch\n")
log2 = read("run2.log")
c2 = [c for c in json.load(open(os.path.join(run, "comments2.json"))) if marker.search(c["body"])]
check(read("run2.conclusion").strip() == "success", "the re-run succeeded")
check('"decision":"allow"' in log2, "the base branch's policy allowed it")
check(c2, f"the findings were posted as review comments with markers ({len(c2)})")
check(all(c["user"]["login"] == identity for c in c2), f"posted as {identity}")
check(any(c["path"] == "calc/calc.go" for c in c2), "a comment sits on calc/calc.go")

print("\n## run 3: a second commit\n")
log3 = read("run3.log")
c3 = [c for c in json.load(open(os.path.join(run, "comments3.json"))) if marker.search(c["body"])]
fps = [marker.search(c["body"]).group(1) for c in c3]
check(read("run3.conclusion").strip() == "success", "the run succeeded")
check("reviewing 1 file(s) changed since" in log3, "an incremental review of the changed file only")
check(len(fps) == len(set(fps)), f"no comment duplicated ({len(fps)} comments, {len(set(fps))} distinct)")
print("\nresult: " + ("PASS" if ok else "FAIL"))
sys.exit(0 if ok else 1)
EOF
